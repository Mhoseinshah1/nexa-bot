/**
 * The largest body a gateway webhook may carry. The documented TonPays body is a few
 * hundred bytes; an unauthenticated route reads no more than it must.
 */
export const GATEWAY_WEBHOOK_BODY_LIMIT_BYTES = 16 * 1024;

/** The route prefix the limit above is applied to, matched by an `onRoute` hook. */
export const GATEWAY_WEBHOOK_ROUTE_PREFIX = GATEWAY_WEBHOOK_PATH_PREFIX;

const tenantIdSchema = z.uuid();

/**
 * External payment gateway webhooks (WP11A, `docs/tonpays-gateway-audit.md` §5.6).
 *
 * `POST /payments/webhook/<provider>/<tenantId>`. The URL is GENERATED by this
 * installation and sent with each invoice; nobody types it.
 *
 * ## A webhook is a hint, never evidence
 *
 * TonPays documents an `X-TonPays-Signature` header and does not document how to verify
 * it, so it is not verified, not read and not logged — and neither is the `X-API-Key`
 * header the provider sends. Nothing a webhook says can settle a payment: it locates the
 * attempt inside the tenant the URL names, deduplicates on the delivery id, records what
 * it hinted and brings the next server-to-server INQUIRY forward. Only that inquiry's
 * answer reaches the settlement path, in the worker.
 *
 * ## The answer does not depend on what exists
 *
 * A well-formed body is answered `{ ok: true }` whether the tenant exists, the attempt
 * exists, the ids match or the delivery is a duplicate — so the endpoint says nothing
 * about which tenants or orders exist, and a provider retrying an unknown id is not
 * encouraged to retry for ever. A body that is not the documented shape is a 400, like
 * every other malformed command here; the provider is not the sender of such a body.
 *
 * ## A signed route (NOWPayments)
 *
 * A route whose descriptor says `webhookSecret` hands the signature header on; the body is
 * verified (HMAC-SHA512 over the key-sorted JSON, constant-time) against the tenant's stored
 * IPN secret before any field is read, and an unverified one is answered `{ ok: true }`
 * like any other ignored webhook — and dropped. A verified one is STILL only a hint.
 *
 * ## An optionally signed route (TetraPay)
 *
 * `X-TetraPay-Signature: t=<unix>,v1=<hex>` is an HMAC-SHA256 of `t + "." + raw_body`, so the
 * RAW bytes are handed on (`raw-body.ts` keeps them for this route). With a secret stored, a
 * bad, stale (>300 s) or unsigned webhook is dropped unread and raises the one unverified
 * alert; with none stored, the webhook is an unauthenticated hint. Either way it is deduplicated
 * on `X-TetraPay-Event-Id` and STILL only brings the verify forward - the verify decides.
 *
 * ## An optionally signed route that REFUSES (TonPays, R7)
 *
 * `X-TonPays-Signature: t=<unix>,v1=<hex>` is the same scheme over the raw bytes
 * (`docs/tonpays-gateway-audit.md` §5.6, from TonPays support 2026-10-24). With a webhook secret
 * stored in Nexa the signature is REQUIRED: a missing, bad, stale or unreadable-secret webhook is
 * answered 401 (TonPays retries any non-2xx), records only the one rolled-up
 * `tonpays.webhook.signature_rejected` condition and triggers no inquiry. With none stored it is
 * accepted as before, a hint that only brings the inquiry forward. `t` is the send time of the
 * attempt, so it bounds clock skew and is never a dedupe key: that is `X-TonPays-Delivery-Id`.
 *
 * ## An unsigned route (Rialit, Round 9)
 *
 * Rialit signs nothing ("do not trust the body alone"). Its webhook is an unauthenticated hint,
 * deduplicated on `X-Rialit-Delivery` (the body's `event_id`), answered `{ ok: true }` at once,
 * and it only brings `GET /status/{token}` forward — that read alone decides. Its dashboard's
 * `webhook.test` is answered `{ ok: true }` and nothing else happens. Rialit asks for an IP
 * allow-list of its senders; Nexa has no per-route client-address machinery and the addresses
 * are shown only in Rialit's dashboard, so none is enforced: a forged webhook can at most bring
 * a rate-limited read forward (`docs/rialit-gateway-audit.md`, decision D6).
 *
 * ## The custom gateway (Round 10 C1)
 *
 * Nexa's own protocol (`docs/protocols/custom-gateway.md` §3.3): `X-Nexa-Bridge-Signature`
 * (`t=,v1=`) over `NEXA-CGW-V1-CALLBACK\n<t>\n` + the raw bytes, keyed by the route's ONE secret,
 * verified before any field is read; `X-Nexa-Delivery-Id` (equal to the body's `delivery_id`) is
 * the dedupe key. A bad or stale signature is answered 401 so the bridge retries after fixing its
 * secret or clock; a sender outside the route's IP allow-list 403, before the signature is even
 * read (`request.ip`, as the trusted reverse proxy reports it). Still a hint: it only brings the
 * signed inquiry forward.
 *
 * No external call is made here, and no money moves here.
 */
@Controller()
export class GatewayWebhookController {
  constructor(@Inject(CONTAINER) private readonly container: Container) {}

  @Post(`${GATEWAY_WEBHOOK_PATH_PREFIX}/:provider/:tenantId`)
  @HttpCode(200)
  async receive(
    @Param('provider') providerParam: string,
    @Param('tenantId') tenantIdParam: string,
    @Headers(TONPAYS_DELIVERY_ID_HEADER) deliveryId: string | undefined,
    /*
     * NOWPayments' IPN signature (`docs/nowpayments-gateway-audit.md` §5.6). Read ONLY for a
     * route whose descriptor says its provider signs; the service verifies it against the
     * tenant's stored secret before any field of the body is read. Never logged.
     */
    @Headers(NOWPAYMENTS_SIGNATURE_HEADER) signature: string | undefined,
    // TetraPay's signature and its stable event id (the dedupe key). Same rule: read only for
    // a route whose descriptor says its provider signs.
    @Headers(TETRAPAY_SIGNATURE_HEADER) tetrapaySignature: string | undefined,
    @Headers(TETRAPAY_EVENT_ID_HEADER) tetrapayEventId: string | undefined,
    // Rialit's stable event id (the dedupe key). Rialit signs nothing.
    @Headers(RIALIT_DELIVERY_HEADER) rialitDeliveryId: string | undefined,
    // TonPays' signature (same rule: read only for a route whose descriptor says it signs).
    @Headers(TONPAYS_SIGNATURE_HEADER) tonpaysSignature: string | undefined,
    // Round 10 C1: the custom gateway's bridge signature and delivery id.
    @Headers(CUSTOM_GATEWAY_HEADERS.bridgeSignature) bridgeSignature: string | undefined,
    @Headers(CUSTOM_GATEWAY_HEADERS.deliveryId) bridgeDeliveryId: string | undefined,
    @Req() request: unknown,
    @Body() body: unknown,
  ): Promise<{ ok: true }> {
    const provider = externalProviderOf(providerParam);
    if (provider === null) {
      throw errors.notFound(COMMERCE_ERROR_CODES.PAYMENT_GATEWAY_NOT_FOUND, 'Unknown route.');
    }
    const tenant = tenantIdSchema.safeParse(tenantIdParam);
    if (!tenant.success) return { ok: true };

    const descriptor = PAYMENT_GATEWAY_DESCRIPTORS[provider];
    const custom = descriptor.webhookSignedByCredential;
    const result = await this.container.gatewayPayments.receiveWebhook(
      tenant.data,
      provider,
      body,
      // The custom gateway's dedupe key is ITS header alone, never another provider's.
      custom
        ? bridgeDeliveryId
        : (deliveryId ??
            (provider === 'TETRAPAY'
              ? tetrapayEventId
              : provider === 'RIALIT'
                ? rialitDeliveryId
                : undefined)),
      custom
        ? bridgeSignature
        : descriptor.webhookSecret
          ? provider === 'TETRAPAY'
            ? tetrapaySignature
            : provider === 'TONPAYS' || provider === 'TONPAYS_TELEGRAM'
              ? tonpaysSignature
              : signature
          : undefined,
      rawBodyOf(request),
      // Round 10 C1: the sender, as the trusted reverse proxy reported it, for the allow-list.
      descriptor.operatorEndpoint ? sourceIpOf(request) : undefined,
    );
    // TonPays and the custom gateway ask for a refusal they can see (and retry any non-2xx); the
    // other signed routes keep answering `{ ok: true }` to an unverified webhook.
    if (
      result === 'IGNORED_UNVERIFIED' &&
      (provider === 'TONPAYS' || provider === 'TONPAYS_TELEGRAM' || custom)
    ) {
      throw new UnauthorizedException('Webhook signature not verified.');
    }
    if (result === 'IGNORED_SOURCE') {
      throw new ForbiddenException('Webhook sender not allowed.');
    }
    if (result === 'MALFORMED') {
      throw errors.validation(
        COMMERCE_ERROR_CODES.COMMERCE_REQUEST_INVALID,
        'That is not a payment gateway notification.',
      );
    }
    return { ok: true };
  }
}

/** The provider an URL segment names, if it is an EXTERNAL route of the closed catalogue. */
function externalProviderOf(segment: string): PaymentGatewayProvider | null {
  const found = PAYMENT_GATEWAY_PROVIDERS.find((provider) => provider.toLowerCase() === segment);
  if (found === undefined) return null;
  // A browser-return route (CentralPay) documents no webhook: there is nothing to receive.
  const descriptor = PAYMENT_GATEWAY_DESCRIPTORS[found];
  return descriptor.settlesVia === 'GATEWAY' && !descriptor.browserReturn ? found : null;
}

/** Fastify's `request.ip` (behind the trusted proxies only), or undefined. Never a raw header. */
function sourceIpOf(request: unknown): string | undefined {
  const ip = (request as { ip?: unknown } | null | undefined)?.ip;
  return typeof ip === 'string' && ip.length > 0 ? ip : undefined;
}
