/**
 * Families of codes built at run time (`OPS_ERROR_EVENTS` entries with `prefix: true`): a code
 * of the family with no exact name above is called by its family, never by raw English.
 */
export const OPERATIONAL_EVENT_FAMILY_LABELS_FA: Readonly<Record<string, string>> = {
  'panel.health.': 'وضعیت سلامت پنل',
  'admin.': 'رویداد مدیران',
  'incident.': 'رویداد حادثه',
  'maintenance.': 'رویداد نگهداری',
};

/** The Persian name of an operational-event code (exact, then its family), or null. */
export function operationalEventLabelFa(code: string): string | null {
  if (Object.hasOwn(OPERATIONAL_EVENT_LABELS_FA, code)) {
    return OPERATIONAL_EVENT_LABELS_FA[code] ?? null;
  }
  const family = Object.keys(OPERATIONAL_EVENT_FAMILY_LABELS_FA)
    .filter((prefix) => code.startsWith(prefix))
    .sort((a, b) => b.length - a.length)[0];
  return family === undefined ? null : (OPERATIONAL_EVENT_FAMILY_LABELS_FA[family] ?? null);
}
