import { z } from 'zod';

/**
 * Short public codes (Round 4, PR-C): the identity an operator and a customer QUOTE.
 *
 * Every primary and foreign key stays a UUIDv7 and stays internal. A UUID is what the
 * database joins on; a 36-character value is not something a person reads off a screen,
 * says on the phone or types into a search box, and the Web Admin printed it on every
 * detail page. These codes are presentation identities beside the key — never a key,
 * never a credential, never something anything authorises on.
 *
 * ## Orders, services, payments, tickets: eight characters
 *
 * Crockford base32 with the owner's exclusions: Crockford already leaves out I, L, O and
 * U; the owner also removed 0 and 1, so no character can be misread as another. That is
 * 30 symbols, 30^8 ≈ 6.6 × 10^11 codes per tenant and table.
 *
 * Generated by the DATABASE at insert (`nexa_assign_public_code`, migration 0263), so
 * every writer — the application, the one-time import, a fixture, the release running
 * beside this one during an update — gets one without remembering to ask. The trigger
 * draws a candidate, looks for it in the tenant's rows and draws again on a collision;
 * `<table>_tenant_code_key` (unique, built online) is the arbiter for the race the lookup
 * cannot see. Once written a code never changes (`nexa_public_code_frozen`).
 *
 * ## Products: `P-<number>`
 *
 * A catalogue is tens of rows per tenant and an operator says "P-102" aloud, so a
 * product's code is a per-tenant sequence number from 101, assigned at insert under a
 * per-tenant advisory lock (`nexa_assign_product_code`).
 *
 * ## Customers and panels get no code
 *
 * A customer is the numeric Telegram id plus name / @username (what Telegram shows them);
 * a panel is its name. Neither is invented here.
 */
export const PUBLIC_CODE_ALPHABET = '23456789ABCDEFGHJKMNPQRSTVWXYZ';
export const PUBLIC_CODE_LENGTH = 8;
export const PUBLIC_CODE_PATTERN = /^[2-9A-HJKMNP-TV-Z]{8}$/;

export const publicCodeSchema = z.string().regex(PUBLIC_CODE_PATTERN);

export function isPublicCode(value: string): boolean {
  return PUBLIC_CODE_PATTERN.test(value);
}

/**
 * What a typed search term would be as an 8-character public code, or null.
 *
 * Case and surrounding whitespace are forgiven (a code read aloud or retyped from a
 * screenshot), and so is a leading `#`. Nothing else is "corrected": a typed `0` or `O`
 * is not silently turned into another symbol, because a guessed correction is a search
 * that opens a record the operator did not ask for.
 */
export function publicCodeFromSearch(term: string): string | null {
  const value = term.trim().replace(/^#/u, '').toUpperCase();
  return PUBLIC_CODE_PATTERN.test(value) ? value : null;
}

/** The first number a tenant's products are given. `P-101` is the first product. */
export const PRODUCT_CODE_FIRST_NUMBER = 101;
export const PRODUCT_CODE_PREFIX = 'P-';
const PRODUCT_CODE_SEARCH = /^P-?([1-9][0-9]{0,8})$/u;

/** `P-102`, from the stored per-tenant number. */
export function productCode(codeNumber: number): string {
  return `${PRODUCT_CODE_PREFIX}${codeNumber}`;
}

/** The stored number a typed `P-102` / `p102` names, or null. A bare number is not one. */
export function productCodeNumberFromSearch(term: string): number | null {
  const match = PRODUCT_CODE_SEARCH.exec(term.trim().toUpperCase());
  return match === null ? null : Number(match[1]);
}

/**
 * THE order code accessor — what every surface (bot, Web Admin, ops log) prints for an
 * order. Null only for a row the backfill has not reached, which a surface renders as an
 * absence (an em dash), never as the uuid.
 */
export function orderCodeOf(order: { readonly code: string | null }): string | null {
  return order.code;
}

/** The service code accessor; the same contract as `orderCodeOf`. */
export function serviceCodeOf(service: { readonly code: string | null }): string | null {
  return service.code;
}

/** The ticket code accessor; the same contract as `orderCodeOf`. */
export function ticketCodeOf(ticket: { readonly code: string | null }): string | null {
  return ticket.code;
}

/**
 * The pre-invoice templates that carry `{orderCode}` since PR-C. A tenant override of one of
 * them saved before then cannot carry the code, and template bodies are stored raw and never
 * rewritten, so the resolver PREPENDS `ORDER_CODE_LINE_KEY` to such an override at render
 * time — for these keys only, and only when the override has no `{orderCode}` of its own —
 * the same arrangement `TRACKING_CODE_LINE_KEYS` uses for the payment tracking code.
 */
export const ORDER_CODE_LINE_KEYS = ['bot.order.preinvoice'] as const;

/** The line itself, as a template key, so its words live in the catalogue. */
export const ORDER_CODE_LINE_KEY = 'bot.order.order_code_line' as const;
